/** Defines the OW-097 arbiter answer rules once so its prompt and judge use the same policy. */
import { PROBE_LIMITS } from '../meta/arbiter-probe-receipts.mjs';

const DEFAULT = Object.freeze(['default']);

export const RULES = Object.freeze({
  'arbiter-citation-path': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Use a non-empty repository-relative file path in each evidence location and prose citation.',
    message: ({ field, label }) => `${field} ${JSON.stringify(label)}: use a repository-relative path:line or path:line-line address.`,
    data: Object.freeze(['field', 'label']),
  }),
  'arbiter-citation-existing-file': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Cite an existing file under repoRoot, never a directory, absolute path or path escaping repoRoot, including through a symlink.',
    message: ({ field, label }) => `${field} ${JSON.stringify(label)}: cite an existing file under repoRoot.`,
    data: Object.freeze(['field', 'label']),
  }),
  'arbiter-citation-readable-file': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Cite only files whose contents can be read under repoRoot.',
    message: ({ field, label }) => `${field} ${JSON.stringify(label)}: cite a readable file under repoRoot.`,
    data: Object.freeze(['field', 'label']),
  }),
  'arbiter-citation-line-range': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: "Use safe integer line numbers with 1 <= line_start <= line_end <= the file's last line. An empty file has no valid line range.",
    message: ({ field, label, count }) => `${field} ${JSON.stringify(label)}: use an ascending line range within this file's ${count} lines.`,
    data: Object.freeze(['field', 'label', 'count']),
  }),
  'arbiter-citation-allowed-path': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Cite only files listed under ## Paths or files within directories listed there.',
    message: ({ field, label }) => `${field} ${JSON.stringify(label)}: cite a file listed under ## Paths or within a listed directory.`,
    data: Object.freeze(['field', 'label']),
  }),
  'arbiter-prose-address': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Write prose code addresses as repository-relative path:line or path:line-line, including quoted addresses.',
    message: ({ field, label }) => `${field} ${JSON.stringify(label)}: use a repository-relative path:line or path:line-line address.`,
    data: Object.freeze(['field', 'label']),
  }),
  'arbiter-control-character': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Exclude control characters U+0000 through U+0008, U+000B, U+000C and U+000E through U+001F from every text field.',
    message: ({ field, codePoint }) => `integrity ${field}: remove control character ${codePoint}.`,
    data: Object.freeze(['field', 'codePoint']),
  }),
  'arbiter-lone-surrogate': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Exclude unpaired UTF-16 surrogates from every text field.',
    message: ({ field, codePoint }) => `integrity ${field}: remove lone surrogate ${codePoint}.`,
    data: Object.freeze(['field', 'codePoint']),
  }),
  'arbiter-recommendation-required': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Include at least one task option id in recommendation.option_ids.',
    message: () => 'recommendation.option_ids: recommend at least one task option.',
    data: Object.freeze([]),
  }),
  'arbiter-recommendation-option-id': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Use only task option ids in recommendation.option_ids.',
    message: ({ id }) => `recommendation.option_ids ${JSON.stringify(id)}: unknown task option.`,
    data: Object.freeze(['id']),
  }),
  'arbiter-recommendation-duplicate': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Include each recommended task option id only once in recommendation.option_ids.',
    message: ({ id }) => `recommendation.option_ids ${JSON.stringify(id)}: duplicate entry.`,
    data: Object.freeze(['id']),
  }),
  'arbiter-mix-rationale': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'When recommending multiple options, explain in mix_rationale what each recommended option contributes.',
    message: () => 'recommendation.mix_rationale: explain what each recommended option contributes.',
    data: Object.freeze([]),
  }),
  'arbiter-coverage-duplicate': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Use each option_id at most once per rejected or residual_gaps list and each run name at most once in prior_advice_review.',
    message: ({ field, id }) => `${field} ${JSON.stringify(id)}: duplicate entry.`,
    data: Object.freeze(['field', 'id']),
  }),
  'arbiter-coverage-unexpected': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Use only non-recommended task options in rejected, task options in residual_gaps and supplied prior run names in prior_advice_review.',
    message: ({ field, id }) => `${field} ${JSON.stringify(id)}: unexpected entry.`,
    data: Object.freeze(['field', 'id']),
  }),
  'arbiter-coverage-missing': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Cover every non-recommended task option in rejected, every task option in residual_gaps and every supplied prior run in prior_advice_review.',
    message: ({ field, id }) => `${field}: missing ${JSON.stringify(id)}.`,
    data: Object.freeze(['field', 'id']),
  }),
  'arbiter-pre-mortem-count': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Include between 1 and 5 scenarios in pre_mortem.',
    message: () => 'pre_mortem: provide between 1 and 5 scenarios.',
    data: Object.freeze([]),
  }),
  // OW-097 D3 requires a unique receipt from the current run for every claimed probe.
  'arbiter-probe-count': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Keep the probes list within the probe limit.',
    message: ({ count, max }) => `probes: claimed ${count} probes, with a limit of ${max}.`,
    data: Object.freeze(['count', 'max']),
  }),
  'arbiter-probe-capture-incomplete': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Base probe claims on a complete command-event capture from the current run.',
    message: () => 'probes: the command-event capture is incomplete, so probe bindings cannot be verified.',
    data: Object.freeze([]),
  }),
  'arbiter-probe-tag-shape': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Copy the tag verbatim from the command comment into probe_tag, using the exact prefix and lowercase hex format.',
    message: ({ index, tag }) => `probes[${index}] ${JSON.stringify(tag)}: the tag has an invalid format.`,
    data: Object.freeze(['index', 'tag']),
  }),
  'arbiter-probe-tag-duplicate': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'List each probe tag only once in the result.',
    message: ({ index, tag }) => `probes[${index}] ${JSON.stringify(tag)}: the result already claims this tag.`,
    data: Object.freeze(['index', 'tag']),
  }),
  'arbiter-probe-unmatched': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Include the full tag in the command you actually run for each probe you claim.',
    message: ({ index, tag }) => `probes[${index}] ${JSON.stringify(tag)}: no command event contains this tag.`,
    data: Object.freeze(['index', 'tag']),
  }),
  'arbiter-probe-incomplete': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Wait for each probe command to finish before claiming it.',
    message: ({ index, tag }) => `probes[${index}] ${JSON.stringify(tag)}: the matching command has no completion event.`,
    data: Object.freeze(['index', 'tag']),
  }),
  'arbiter-probe-ambiguous': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Give each attempt its own tag, including a retry after a failed command.',
    message: ({ index, tag, count }) => `probes[${index}] ${JSON.stringify(tag)}: ${count} completed command events contain this tag.`,
    data: Object.freeze(['index', 'tag', 'count']),
  }),
  'arbiter-probe-multiple-markers': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Put only one probe tag in a probe command, including anywhere in its script or arguments.',
    message: ({ index, tag }) => `probes[${index}] ${JSON.stringify(tag)}: the matching command contains another probe tag.`,
    data: Object.freeze(['index', 'tag']),
  }),
  'arbiter-probe-command-too-long': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: `Keep each probe command within ${PROBE_LIMITS.commandBytes} UTF-8 bytes, allowing for shell wrappers.`,
    message: ({ index, tag, bytes, max }) => `probes[${index}] ${JSON.stringify(tag)}: the command uses ${bytes} UTF-8 bytes, with a limit of ${max}.`,
    data: Object.freeze(['index', 'tag', 'bytes', 'max']),
  }),
  'arbiter-probe-terminal-invalid': Object.freeze({
    phases: DEFAULT,
    when: 'always',
    rule: 'Report the outcome of each probe from its completed command result. Describe unsuccessful attempts as failures.',
    message: ({ index, tag }) =>
      `probes[${index}] ${JSON.stringify(tag)}: the matching completion has an invalid command id, status, exit code or output.`,
    data: Object.freeze(['index', 'tag']),
  }),
});
